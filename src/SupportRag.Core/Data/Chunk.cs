using NpgsqlTypes;
using Pgvector;

namespace SupportRag.Core.Data;

/// <summary>
/// One passage of the corpus. The id is the chunker's stable id (a hash of source + title + position), so a
/// re-ingest updates in place; <see cref="ContentHash"/> says whether the text changed and
/// <see cref="EmbeddingModel"/> whether the vector was made by the model we are querying with. Either
/// mismatch means "embed again"; neither means "leave it alone", which is what makes the nightly ingest cheap.
/// </summary>
public sealed class Chunk
{
    public required string Id { get; set; }

    /// <summary>faq | manual | changelog | page — the licensing pin filters on "faq".</summary>
    public required string Source { get; set; }

    public required string Title { get; set; }

    public string Url { get; set; } = "";

    public required string Text { get; set; }

    public required string ContentHash { get; set; }

    public string? EmbeddingModel { get; set; }

    public Vector? Embedding { get; set; }

    /// <summary>Generated by Postgres from title + text; the keyword half of hybrid retrieval.</summary>
    public NpgsqlTsVector SearchVector { get; private set; } = null!;

    public DateTimeOffset UpdatedAt { get; set; }
}
